const CHARS = Object.keys(RAW);
const INDEX = {};
CHARS.forEach((c, i) => { INDEX[c] = i; });
const GW = 5, GH = 7, ADV = 6;
const atlases = {};

function atlasFor(color) {
  if (atlases[color]) return atlases[color];
  const c = G.U.makeCanvas(CHARS.length * ADV, GH);
  const ctx = c.getContext('2d');
  ctx.fillStyle = color;
  CHARS.forEach((ch, i) => {
    const rows = RAW[ch].split('|');
    for (let y = 0; y < GH; y++) {
      for (let x = 0; x < GW; x++) {
        if (rows[y][x] === '#') ctx.fillRect(i * ADV + x, y, 1, 1);
      }
    }
  });
  atlases[color] = c;
  return c;
}

function measure(str, scale) {
  scale = scale || 1;
  return str.length ? (str.length * ADV - 1) * scale : 0;
}

function drawRaw(ctx, str, x, y, color, scale) {
  const atlas = atlasFor(color);
  for (let i = 0; i < str.length; i++) {
    let ch = str[i];
    if (INDEX[ch] === undefined) ch = ch.toUpperCase();
    const gi = INDEX[ch];
    if (gi === undefined || ch === ' ') continue;
    ctx.drawImage(atlas, gi * ADV, 0, GW, GH, x + i * ADV * scale, y, GW * scale, GH * scale);
  }
}

// opts: color, scale, align ('left'|'center'|'right'), shadow (color), outline (color)
function text(ctx, str, x, y, opts) {
  opts = opts || {};
  str = String(str);
  const scale = opts.scale || 1;
  const w = measure(str, scale);
  if (opts.align === 'center') x -= Math.floor(w / 2);
  else if (opts.align === 'right') x -= w;
  x = Math.round(x);
  y = Math.round(y);
  if (opts.outline) {
    for (let dy = -1; dy <= 1; dy++) {
      for (let dx = -1; dx <= 1; dx++) {
        if (dx || dy) drawRaw(ctx, str, x + dx * Math.max(1, scale >> 1), y + dy * Math.max(1, scale >> 1), opts.outline, scale);
      }
    }
  }
  if (opts.shadow) drawRaw(ctx, str, x + Math.max(1, scale >> 1), y + Math.max(1, scale >> 1), opts.shadow, scale);
  drawRaw(ctx, str, x, y, opts.color || '#fff', scale);
  return w;
}

function glyphRows(ch) {
  return RAW[ch] ? RAW[ch].split('|') : null;
}

G.font = { text, measure, glyphRows, GH, ADV };
